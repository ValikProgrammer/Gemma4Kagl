#!/usr/bin/env python3
"""Write a fixed, stratified smoke-test task list (one instance_id per line).

The list always starts with the 10 v4 tasks, so runs stay comparable, then fills
each repo up to its quota with a seeded random sample of the remaining tasks.

    python3 -I scripts/make_smoke_tasks.py                    # -> smoke_tasks_30.txt
    python3 -I scripts/make_smoke_tasks.py --seed 7 --out x.txt
Use it with: python3 -I scripts/build_smoke_notebook.py --task-file smoke_tasks_30.txt
"""
import argparse
import json
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TASKS = ROOT / "tasks.jsonl"

V4_TASKS = [
    "rich_4070", "requests_7505", "httpx_3672",
    "fastapi_15661", "fastapi_15589", "fastapi_15588", "fastapi_15280",
    "fastapi_15030", "fastapi_14964", "fastapi_14962",
]
# 30 tasks, roughly proportional to tasks.jsonl (fastapi 67, rich 48, requests 13, httpx 1).
QUOTA = {"fastapi/fastapi": 15, "Textualize/rich": 11, "psf/requests": 3, "encode/httpx": 1}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=30)
    ap.add_argument("--out", default=str(ROOT / "smoke_tasks_30.txt"))
    args = ap.parse_args()

    tasks = [json.loads(line) for line in TASKS.read_text(encoding="utf-8").splitlines() if line.strip()]
    repo_of = {t["instance_id"]: t["repo"] for t in tasks}
    missing = [i for i in V4_TASKS if i not in repo_of]
    assert not missing, f"v4 tasks not in tasks.jsonl: {missing}"

    rng = random.Random(args.seed)
    picked = list(V4_TASKS)
    for repo, quota in QUOTA.items():
        have = sum(repo_of[i] == repo for i in picked)
        pool = sorted(i for i, r in repo_of.items() if r == repo and i not in picked)
        picked += rng.sample(pool, quota - have)

    lines = [
        f"# {len(picked)} smoke tasks: first the 10 v4 tasks, then a seeded sample (seed={args.seed}).",
        "# Generated by scripts/make_smoke_tasks.py. One instance_id per line; '#' starts a comment.",
        *picked,
    ]
    Path(args.out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    counts = {r: sum(repo_of[i] == r for i in picked) for r in QUOTA}
    print(f"wrote {args.out}: {len(picked)} tasks {counts}")


if __name__ == "__main__":
    main()
